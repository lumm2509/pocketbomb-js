import fs from "node:fs";
import path from "node:path";
import { minifyIntrospection, preprocessIntrospection } from "@gql.tada/internal";
import {
  buildClientSchema,
  getIntrospectionQuery,
  printSchema,
  type IntrospectionQuery,
} from "graphql";

import { DEFAULT_ENV_FILE, DEFAULT_SCHEMA_FILE } from "../shared/constants";

export { DEFAULT_ENV_FILE, DEFAULT_SCHEMA_FILE };

export interface IntrospectOptions {
  /** The PocketBomb URL. */
  url: string;
  /** The public API key (the GraphQL API requires client credentials). */
  publicKey?: string;
  fetch?: typeof fetch;
}

/**
 * Introspects the PocketBomb GraphQL API (`POST /api/graphql`; the introspection
 * fields are not counted in the query limits).
 *
 * @throws {Error} for the HTTP and GraphQL errors.
 */
export async function introspect(options: IntrospectOptions): Promise<IntrospectionQuery> {
  const headers: Record<string, string> = { "content-type": "application/json" };
  if (options.publicKey) {
    headers["X-PB-Public-Key"] = options.publicKey;
  }

  const endpoint = options.url.replace(/\/+$/, "") + "/api/graphql";
  const response = await (options.fetch || fetch)(endpoint, {
    method: "POST",
    headers,
    body: JSON.stringify({ query: getIntrospectionQuery({ descriptions: true }) }),
  });

  let body: any = null;
  try {
    body = await response.json();
  } catch {
    body = null;
  }

  if (!response.ok) {
    throw new Error(
      `The GraphQL introspection failed (${response.status}): ${body?.message || JSON.stringify(body)}`,
    );
  }
  if (body?.errors?.length || !body?.data?.__schema) {
    throw new Error(
      "The GraphQL introspection failed: " +
        (body?.errors?.map((e: any) => e.message).join("; ") || "no schema"),
    );
  }

  return body.data as IntrospectionQuery;
}

/**
 * Returns a copy of the introspection without the empty descriptions
 * (the server reports "" for the undocumented fields).
 */
export function withoutEmptyDescriptions<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map(withoutEmptyDescriptions) as T;
  }

  if (value && typeof value === "object") {
    const result: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) {
      result[key] = key === "description" && item === "" ? null : withoutEmptyDescriptions(item);
    }
    return result as T;
  }

  return value;
}

/**
 * Returns the GraphQL SDL of an introspection.
 */
export function introspectionToSDL(introspection: IntrospectionQuery): string {
  return printSchema(buildClientSchema(withoutEmptyDescriptions(introspection))) + "\n";
}

/**
 * Returns the `pocketbomb-env.d.ts` of an introspection: the gql.tada introspection type
 * and the `@pocketbomb/dynamite/graphql` schema augmentation used by `graphql()`.
 */
export function introspectionToEnv(introspection: IntrospectionQuery): string {
  const type = preprocessIntrospection(minifyIntrospection(introspection));

  return (
    "/* eslint-disable */\n" +
    "/* prettier-ignore */\n" +
    "// Generated by `dynamite codegen` from the PocketBomb GraphQL API. Do not edit.\n\n" +
    "/** The gql.tada introspection of the PocketBomb GraphQL schema. */\n" +
    "export type introspection = " +
    type +
    ";\n\n" +
    'declare module "@pocketbomb/dynamite/graphql" {\n' +
    "  interface PocketBombSchema {\n" +
    "    introspection: introspection;\n" +
    "  }\n" +
    "}\n"
  );
}

export interface GenerateOptions {
  /** The project root (default to the current working dir). */
  cwd?: string;
  /** The SDL output (default to `.dynamite/schema.graphql`). */
  schemaFile?: string;
  /** The gql.tada env output (default to `pocketbomb-env.d.ts`). */
  envFile?: string;
}

export interface GenerateResult {
  schemaFile: string;
  envFile: string;
  /** Whether a file was (re)written. */
  changed: boolean;
}

function writeIfChanged(file: string, content: string): boolean {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) {
    return false;
  }

  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);

  return true;
}

/**
 * Writes the schema SDL and the gql.tada env of an introspection (only if they changed).
 */
export function generate(
  introspection: IntrospectionQuery,
  options: GenerateOptions = {},
): GenerateResult {
  const cwd = options.cwd || process.cwd();
  const schemaFile = path.resolve(cwd, options.schemaFile || DEFAULT_SCHEMA_FILE);
  const envFile = path.resolve(cwd, options.envFile || DEFAULT_ENV_FILE);

  const schemaChanged = writeIfChanged(schemaFile, introspectionToSDL(introspection));
  const envChanged = writeIfChanged(envFile, introspectionToEnv(introspection));

  return { schemaFile, envFile, changed: schemaChanged || envChanged };
}

export interface CodegenOptions extends IntrospectOptions, GenerateOptions {}

/**
 * Introspects the API and writes the schema and the env (see {@link generate}).
 */
export async function codegen(options: CodegenOptions): Promise<GenerateResult> {
  return generate(await introspect(options), options);
}

export interface WatchOptions extends CodegenOptions {
  /** The schema poll interval in ms (default to 2000). */
  interval?: number;
  /** Called after every generation that changed a file. */
  onChange?: (result: GenerateResult) => void;
  /** Called for the failed polls (the watcher keeps running). */
  onError?: (err: unknown) => void;
}

/**
 * Regenerates the schema and the env when the API schema changes (polling).
 * Returns a function that stops the watcher.
 */
export function watchCodegen(options: WatchOptions): () => void {
  let stopped = false;
  let timer: ReturnType<typeof setTimeout> | undefined;

  const tick = async () => {
    try {
      const result = await codegen(options);
      if (result.changed) {
        options.onChange?.(result);
      }
    } catch (err) {
      options.onError?.(err);
    }

    if (!stopped) {
      timer = setTimeout(tick, options.interval ?? 2000);
    }
  };

  void tick();

  return () => {
    stopped = true;
    clearTimeout(timer);
  };
}
